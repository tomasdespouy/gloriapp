/**
 * Genera la migración SQL con los 34 UPDATEs a partir de C:/tmp/enriched-blocks.json
 * Output: supabase/migrations/20260508120100_seed_enrichment_blocks.sql
 *
 * Reproducible: si los bloques se regeneran, este script produce un SQL nuevo.
 */
const fs = require("fs");

const ENRICHED = JSON.parse(fs.readFileSync("C:/tmp/enriched-blocks.json", "utf8"));
const ts = new Date().toISOString();

const HEADER = `-- ============================================================
-- Migration: seed enrichment blocks for the 34 active patients (INF-2026-050)
-- Date: 2026-05-08
-- Source: C:/tmp/enriched-blocks.json (generated by docs/gen-enrichment-blocks.js)
-- Generator model: gpt-4o · Temperature: 0.7
-- Generated at: ${ENRICHED.generated_at}
-- Total patients: ${ENRICHED.successes}/${ENRICHED.patients.length}
--
-- Each UPDATE writes 4 JSONB blocks:
--   { "text": "...", "version": 1, "generated_by": "ai",
--     "generated_at": "${ts}", "model": "gpt-4o" }
--
-- The system_prompt column is NOT touched. Composition happens at runtime
-- in src/lib/build-system-prompt.ts. Reversal: see schema migration header.
--
-- Wrapped in a single transaction. UPDATEs son idempotentes (WHERE id = '...'
-- no falla si el id no existe). INSERTs en enrichment_history usan WHERE EXISTS
-- para saltarse silenciosamente pacientes que no están en este ambiente
-- (STAGING tiene 23, PROD tiene 34 — el mismo SQL sirve para ambos).
-- ============================================================

BEGIN;

`;

const FOOTER = `

COMMIT;

-- ============================================================
-- Verification queries (manual run after migration):
--
-- SELECT count(*) FROM ai_patients WHERE enrichment_version > 0;     -- expect 34
-- SELECT count(*) FROM enrichment_history;                            -- expect 136 (34 × 4)
-- SELECT name, jsonb_typeof(enrichment_red_social) FROM ai_patients   -- expect 'object'
--   ORDER BY name LIMIT 5;
-- ============================================================
`;

// Postgres dollar-quoting con un tag único por paciente para evitar colisiones
function dollarQuote(text, tag) {
  // Si el texto tiene $tag$, generamos uno alterno
  let useTag = tag;
  let attempt = 0;
  while (text.includes(`$${useTag}$`)) {
    attempt++;
    useTag = tag + attempt;
  }
  return `$${useTag}$${text}$${useTag}$`;
}

function blockJson(text, model = "gpt-4o") {
  return {
    text,
    version: 1,
    generated_by: "ai",
    generated_at: ts,
    model,
  };
}

function jsonbLiteral(obj, tag) {
  return dollarQuote(JSON.stringify(obj), tag);
}

const lines = [HEADER];

let nUpdates = 0;
for (const p of ENRICHED.patients) {
  if (!p.enriched_blocks) {
    lines.push(`-- SKIPPED ${p.name} (${p.id}) — no enriched_blocks`);
    continue;
  }
  const b = p.enriched_blocks;
  const tag = "blk";

  const rs = blockJson(b.red_social_y_vinculos);
  const lu = blockJson(b.lugares_significativos);
  const ec = blockJson(b.estado_corporal_y_rutina);
  const ft = blockJson(b.frases_tipo_que_dices);

  lines.push(`-- ── ${p.name} (${p.country} / ${p.difficulty})`);
  // UPDATE no falla si el id no existe (afecta 0 filas); idempotente entre ambientes
  lines.push(`UPDATE public.ai_patients SET`);
  lines.push(`  enrichment_red_social = ${jsonbLiteral(rs, tag)}::jsonb,`);
  lines.push(`  enrichment_lugares = ${jsonbLiteral(lu, tag)}::jsonb,`);
  lines.push(`  enrichment_estado_corporal = ${jsonbLiteral(ec, tag)}::jsonb,`);
  lines.push(`  enrichment_frases_tipo = ${jsonbLiteral(ft, tag)}::jsonb,`);
  lines.push(`  enrichment_version = 1,`);
  lines.push(`  updated_at = NOW()`);
  lines.push(`WHERE id = '${p.id}';`);
  lines.push("");

  // Audit trail: 4 INSERTs condicionales con WHERE EXISTS — se saltan silenciosamente
  // si el patient_id no está en este ambiente (STAGING vs PROD).
  for (const [block_name, blob] of [
    ["red_social", rs], ["lugares", lu], ["estado_corporal", ec], ["frases_tipo", ft]
  ]) {
    lines.push(
      `INSERT INTO public.enrichment_history (patient_id, block_name, version, content, generated_by, created_at)\n` +
      `  SELECT '${p.id}'::uuid, '${block_name}', 1, ${jsonbLiteral(blob, "h")}::jsonb, 'ai', NOW()\n` +
      `  WHERE EXISTS (SELECT 1 FROM public.ai_patients WHERE id = '${p.id}');`
    );
  }
  lines.push("");
  nUpdates++;
}

lines.push(FOOTER);

const out = "supabase/migrations/20260508120100_seed_enrichment_blocks.sql";
fs.writeFileSync(out, lines.join("\n"));
const size = fs.statSync(out).size;
console.log(`Generated: ${out}`);
console.log(`Size: ${(size / 1024).toFixed(1)} KB`);
console.log(`Updates: ${nUpdates}/${ENRICHED.patients.length}`);
console.log(`History rows: ${nUpdates * 4}`);
